// → текст ответа или null, если тема не распознана
export function faqAnswer(question, user) {
  const q = String(question || '').toLowerCase().replace(/ё/g, 'е');
  const topic = TOPICS.find((t) => t.re.test(q));
  return topic ? topic.answer(user || {}) : null;
}

export function isCrisis(question) {
  return TOPICS[0].re.test(String(question || '').toLowerCase().replace(/ё/g, 'е'));
}
